/* Dutch translations. Registers into the global I18N (see js/i18n.js).

   Conventions running through the whole file:
   - the reader is addressed with «je», the group with «jullie» — the same
     informal register the German, English, Spanish, French and Italian tables
     use;
   - the app's own vocabulary is fixed: a round is a «groep», the Regal is the
     «kast», a session stays a «sessie» (never «spelavond» — see CLAUDE.md on
     why the entity keeps one name in every language, and
     test/session-naming.test.js, which enforces it for Dutch by banning the
     substring «avond» once the adverbial «vanavond» has been stripped);
   - retiring a game is «opzijleggen», completing it «uitspelen»;
   - «Inloggen»/«Uitloggen» carry log in/log out;
   - the Chronik is «Geschiedenis», the Pokale are «Trofeeën», and the hall of
     fame is the Dutch idiom «Eregalerij».
   Quoted titles use the Dutch double quotes “…”, the same glyphs en.js sets.
   The apostrophe is the typographic ’ (U+2019) throughout — it is what Dutch
   text actually sets (’s avonds, z’n), and it keeps every string
   single-quotable without escapes. Keep it uniform.

   NOTE ON PLURALS: Dutch routes 0 to the PLURAL («0 spellen»), like English,
   German, Spanish and Italian — so tn()'s one/other pair is exact here.
   Singular forms still substitute {n} rather than spelling out a «1», which is
   what test/i18n-parity.test.js pins for every tn() pair in the source. */


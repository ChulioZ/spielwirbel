/* Portuguese translations (Brazilian wording). Registers into the global I18N
   (see js/i18n.js).

   Conventions running through the whole file:
   - the reader is addressed with «você», the group with «vocês» — the same
     informal register the German, English, Spanish, French, Italian and Dutch
     tables use;
   - the app's own vocabulary is fixed: a round is a «grupo», the Regal is the
     «estante», a session stays a «sessão» (never «noite de jogos» — see
     CLAUDE.md on why the entity keeps one name in every language, and
     test/session-naming.test.js, which enforces it for Portuguese by banning
     «noite» once the time-of-day adverbial «hoje à noite» has been stripped);
   - retiring a game is «aposentar», completing it «concluir»;
   - «Entrar»/«Sair» carry log in/log out;
   - the Chronik is «Histórico», the Pokale are «Troféus», and the hall of fame
     is «Galeria da fama».
   Quoted titles use the double quotes “…”, the same glyphs en.js sets. Brazilian
   Portuguese sets no apostrophes of its own, so every string is single-quotable
   without escapes — keep it that way.

   NOTE ON PLURALS: Portuguese puts 0 in the SINGULAR («0 jogo»), like French and
   unlike English, German, Spanish, Italian and Dutch. Every singular form a zero
   can reach must therefore substitute {n} rather than spelling out a «1» —
   test/i18n-parity.test.js pins that for every tn() pair in the source. A
   singular that names no number at all («um dia atrás») is the other correct
   shape and reads fine at any count. */


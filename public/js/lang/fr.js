/* French translations. Registers into the global I18N (see js/i18n.js).

   Conventions running through the whole file:
   - the reader is addressed with «tu», the group with «vous» — the same
     informal register the German, English and Spanish tables use;
   - the app's own vocabulary is fixed: a round is a «groupe», the Regal is
     the «étagère», a session stays a «session» (never «soirée jeux» — see
     CLAUDE.md on why the entity keeps one name in every language);
   - retiring a game is «retirer», completing it «terminer»;
   - «Se connecter»/«Se déconnecter» carry log in/log out.
   French typography uses guillemets «…» and a space before ?, !, : and ;.
   Those spaces are deliberately ORDINARY spaces, not U+00A0: an invisible
   character in a file a native speaker is invited to correct is a trap, and
   the browser's own line-breaking is a smaller cost than a translator
   silently dropping one. Keep it uniform — do not mix the two.

   NOTE ON PLURALS: French puts 0 in the SINGULAR («0 jeu»), unlike English,
   German and Spanish. Every singular form a zero can reach must therefore
   substitute {n} rather than spelling out a «1» — test/i18n-parity.test.js
   pins that for every tn() pair in the source. */

